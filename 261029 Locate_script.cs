    // =========================================================
    // 1. 이전 검사 값이 남지 않도록 먼저 0으로
    //    (못 찾았을 때 이전 점수가 그대로 나가던 문제 방지)
    // =========================================================    
    block.Outputs["AlignScore"].Value = 0.0;

    // =========================================================
    // 2. 블록 안 툴을 순서대로 실행 (PMAlign → Fixture …)
    //    PMAlign이 대상을 못 찾으면 그 뒤 툴(Fixture)은 실행하지 않는다.
    //    (Fixture가 PMAlign Results[0]을 쓰므로 실행하면 바인딩 오류가 난다)
    // =========================================================
    CogPMAlignTool pmAlignTool = null;
    foreach (ICogTool tool in block.Tools)
    {
      block.RunTool(tool, ref message, ref result);

      pmAlignTool = tool as CogPMAlignTool ?? pmAlignTool;
      if (tool is CogPMAlignTool && (pmAlignTool.Results == null || pmAlignTool.Results.Count == 0))
      {
        // 못 찾음: AlignScore = 0, Reject → 프로그램에서 "0.00 - FAIL" (NG)
        result = CogToolResultConstants.Reject;
        return false;
      }
    }
    
    // =========================================================
    // 3. 찾았으면 첫 번째 결과의 점수를 내보냄 (0~1, 기준값 비교는 프로그램 Settings 창)
    // =========================================================
    if (pmAlignTool != null)
    {
      block.Outputs["AlignScore"].Value = pmAlignTool.Results[0].Score;
    }

    // result는 RunTool이 블록 안 툴 결과를 모아 설정한 값을 그대로 사용
    // return false = 스크립트가 툴을 실행했으므로 VisionPro가 다시 실행하지 않음
    return false;    
  }

